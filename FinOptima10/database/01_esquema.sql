-- Si ya tienes la base creada, puedes volver a ejecutarlo: usa "if not exists".

create table if not exists usuarios (
    id integer generated by default as identity primary key,
    nombre_completo text not null,
    correo text not null,
    contrasena_hash text not null,
    contrasena_sal text not null,
    rol text not null default 'Usuario' check (rol in ('Usuario', 'Administrador')),
    activo boolean not null default true,
    intentos_fallidos integer not null default 0,
    bloqueado_hasta timestamp without time zone,
    creado_en timestamp without time zone not null default now(),
    color_acento text not null default '#2F6FED',
    tamano_fuente integer not null default 10,
    tema text not null default 'Claro' check (tema in ('Claro', 'Oscuro', 'Contraste')),
    alertas_deudas boolean not null default true,
    alertas_metas boolean not null default true,
    alertas_presupuesto boolean not null default true,
    alertas_sobres boolean not null default true,
    foto bytea
);

create unique index if not exists ux_usuarios_correo on usuarios (lower(correo));

create table if not exists sobres (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    nombre text not null,
    tipo integer not null,
    porcentaje_objetivo numeric(7, 2) not null default 0,
    porcentaje_minimo numeric(7, 2) not null default 0,
    porcentaje_maximo numeric(7, 2) not null default 100,
    saldo numeric(16, 2) not null default 0,
    descripcion text not null default '',
    activo boolean not null default true,
    constraint ck_sobres_porcentajes check (
        porcentaje_minimo >= 0 and porcentaje_maximo <= 100 and
        porcentaje_minimo <= porcentaje_objetivo and porcentaje_objetivo <= porcentaje_maximo
    ),
    constraint uq_sobres_id_usuario unique (id, usuario_id)
);

create table if not exists movimientos (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    sobre_id integer,
    tipo integer not null check (tipo in (1, 2)),
    categoria text not null,
    descripcion text not null default '',
    monto numeric(16, 2) not null check (monto > 0),
    fecha date not null default current_date,
    constraint fk_movimientos_sobre foreign key (sobre_id, usuario_id)
        references sobres(id, usuario_id) on delete set null (sobre_id)
);

create table if not exists metas (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    nombre text not null,
    monto_objetivo numeric(16, 2) not null check (monto_objetivo > 0),
    monto_actual numeric(16, 2) not null default 0 check (monto_actual >= 0),
    fecha_limite date not null,
    prioridad text not null default 'Media' check (prioridad in ('Baja', 'Media', 'Alta'))
);

create table if not exists deudas (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    acreedor text not null,
    capital numeric(16, 2) not null default 0 check (capital >= 0),
    saldo numeric(16, 2) not null default 0 check (saldo >= 0),
    tasa_interes numeric(8, 4) not null default 0 check (tasa_interes >= 0),
    pago_minimo numeric(16, 2) not null default 0 check (pago_minimo >= 0),
    fecha_vencimiento date not null
);

create table if not exists presupuestos (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    categoria text not null,
    limite numeric(16, 2) not null check (limite > 0),
    anio integer not null check (anio between 2000 and 2100),
    mes integer not null check (mes between 1 and 12)
);

create unique index if not exists ux_presupuestos_periodo on presupuestos (usuario_id, anio, mes, lower(categoria));
create index if not exists ix_presupuestos_usuario_periodo on presupuestos (usuario_id, anio desc, mes desc);

create table if not exists actividad (
    id integer generated by default as identity primary key,
    usuario_id integer not null references usuarios(id) on delete cascade,
    fecha timestamp without time zone not null default now(),
    accion text not null
);

create table if not exists auditoria (
    id bigint generated by default as identity primary key,
    administrador_id integer references usuarios(id) on delete set null,
    fecha timestamp without time zone not null default now(),
    accion text not null,
    detalle text not null default ''
);

create index if not exists ix_movimientos_usuario_fecha on movimientos (usuario_id, fecha desc);
create index if not exists ix_metas_usuario on metas (usuario_id, fecha_limite);
create index if not exists ix_deudas_usuario on deudas (usuario_id, fecha_vencimiento);
create index if not exists ix_actividad_usuario on actividad (usuario_id, fecha desc);
create index if not exists ix_auditoria_fecha on auditoria (fecha desc);
