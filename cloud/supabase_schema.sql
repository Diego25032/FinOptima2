-- FINOPTIMA | Esquema central para Supabase (PostgreSQL)
-- Ejecutar una sola vez en Supabase > SQL Editor.
-- La app de escritorio NO debe usar service_role ni credenciales de PostgreSQL.
-- El cliente se conectará mediante Supabase Auth + REST API + RLS.

create table if not exists public.profiles (
    id integer generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users(id) on delete cascade,
    full_name text not null default '',
    email text not null unique,
    role text not null default 'Usuario' check (role in ('Usuario','Administrador')),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    failed_login_attempts integer not null default 0,
    lockout_until timestamptz
);

create table if not exists public.envelopes (
    id integer generated by default as identity primary key,
    user_id integer not null references public.profiles(id) on delete cascade,
    name text not null,
    type integer not null,
    target_percent numeric(7,2) not null default 0,
    min_percent numeric(7,2) not null default 0,
    max_percent numeric(7,2) not null default 100,
    balance numeric(16,2) not null default 0,
    description text not null default '',
    active boolean not null default true,
    constraint uq_envelopes_id_user unique (id, user_id)
);

create table if not exists public.transactions (
    id integer generated by default as identity primary key,
    user_id integer not null references public.profiles(id) on delete cascade,
    envelope_id integer references public.envelopes(id) on delete set null,
    type integer not null,
    category text not null,
    description text not null default '',
    amount numeric(16,2) not null check (amount >= 0),
    date date not null default current_date,
    constraint fk_transactions_envelope_owner
        foreign key (envelope_id, user_id)
        references public.envelopes(id, user_id)
);

create table if not exists public.goals (
    id integer generated by default as identity primary key,
    user_id integer not null references public.profiles(id) on delete cascade,
    name text not null,
    target_amount numeric(16,2) not null check (target_amount > 0),
    current_amount numeric(16,2) not null default 0,
    deadline date not null,
    priority text not null default 'Media'
);

create table if not exists public.debts (
    id integer generated by default as identity primary key,
    user_id integer not null references public.profiles(id) on delete cascade,
    creditor text not null,
    principal numeric(16,2) not null,
    balance numeric(16,2) not null,
    interest_rate numeric(8,4) not null default 0,
    minimum_payment numeric(16,2) not null default 0,
    due_date date not null
);

create table if not exists public.plans (
    id integer generated by default as identity primary key,
    user_id integer not null references public.profiles(id) on delete cascade,
    month text not null,
    income numeric(16,2) not null default 0,
    allocated numeric(16,2) not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.audit_log (
    id bigint generated by default as identity primary key,
    admin_user_id integer references public.profiles(id) on delete set null,
    action text not null,
    details text not null default '',
    created_at timestamptz not null default now()
);

create index if not exists ix_envelopes_user on public.envelopes(user_id);
create index if not exists ix_transactions_user_date on public.transactions(user_id, date desc);
create index if not exists ix_goals_user on public.goals(user_id);
create index if not exists ix_debts_user_due on public.debts(user_id, due_date);
create index if not exists ix_plans_user on public.plans(user_id);

-- Perfil automático al crear una cuenta en Supabase Auth.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
    insert into public.profiles(auth_user_id, full_name, email)
    values (
        new.id,
        coalesce(new.raw_user_meta_data->>'full_name', split_part(coalesce(new.email,''),'@',1)),
        lower(coalesce(new.email,''))
    )
    on conflict (auth_user_id) do update
       set email = excluded.email;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created_finoptima on auth.users;
create trigger on_auth_user_created_finoptima
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

-- Funciones auxiliares seguras para políticas RLS.
create or replace function public.current_finoptima_profile_id()
returns integer
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
    select id from public.profiles where auth_user_id = auth.uid() and active = true limit 1;
$$;

create or replace function public.current_finoptima_role()
returns text
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
    select role from public.profiles where auth_user_id = auth.uid() and active = true limit 1;
$$;

-- Estas funciones solo se necesitan desde sesiones autenticadas y políticas RLS.
revoke all on function public.current_finoptima_profile_id() from public;
revoke all on function public.current_finoptima_profile_id() from anon;
revoke all on function public.current_finoptima_role() from public;
revoke all on function public.current_finoptima_role() from anon;
grant execute on function public.current_finoptima_profile_id() to authenticated;
grant execute on function public.current_finoptima_role() to authenticated;

