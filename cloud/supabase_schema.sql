-- Perfil: cada persona ve el suyo; administración solo ve perfiles/cuentas, no finanzas.
drop policy if exists "profile_read_self_or_admin" on public.profiles;
create policy "profile_read_self_or_admin" on public.profiles
for select to authenticated
using (auth_user_id = auth.uid() or public.current_finoptima_role() = 'Administrador');

drop policy if exists "profile_update_self" on public.profiles;
create policy "profile_update_self" on public.profiles
for update to authenticated
using (auth_user_id = auth.uid())
with check (auth_user_id = auth.uid() and role = public.current_finoptima_role());

-- El usuario solo puede consultar y modificar registros que pertenezcan a su perfil.
do $$
declare t text;
begin
  foreach t in array array['envelopes','transactions','goals','debts','plans'] loop
    execute format('drop policy if exists %I on public.%I', t || '_owner_only', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (user_id = public.current_finoptima_profile_id()) with check (user_id = public.current_finoptima_profile_id())',
      t || '_owner_only', t
    );
  end loop;
end $$;

-- Auditoría visible únicamente para administradores.
drop policy if exists "audit_admin_read" on public.audit_log;
create policy "audit_admin_read" on public.audit_log
for select to authenticated
using (public.current_finoptima_role() = 'Administrador');

drop policy if exists "audit_admin_insert" on public.audit_log;
create policy "audit_admin_insert" on public.audit_log
for insert to authenticated
with check (public.current_finoptima_role() = 'Administrador'
            and admin_user_id = public.current_finoptima_profile_id());


-- Única vía de administración de roles/estado desde la app.
-- Supabase RPC ejecuta esta función con permisos controlados; nunca se concede UPDATE(role) al cliente.
create or replace function public.admin_update_profile(
    target_profile_id integer,
    new_role text,
    new_active boolean
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    target_auth uuid;
    target_email text;
begin
    if public.current_finoptima_role() <> 'Administrador' then
        raise exception 'No autorizado';
    end if;
    if new_role not in ('Usuario','Administrador') then
        raise exception 'Rol no válido';
    end if;

    select auth_user_id, email into target_auth, target_email
    from public.profiles where id = target_profile_id for update;

    if target_auth is null then
        raise exception 'Cuenta no encontrada';
    end if;

    if target_auth = auth.uid() and (new_role <> 'Administrador' or not new_active) then
        raise exception 'No puedes quitar tus propios permisos ni desactivar tu sesión';
    end if;

    if exists (
        select 1 from public.profiles
        where role = 'Administrador' and active = true
          and id <> target_profile_id
    ) = false and (new_role <> 'Administrador' or not new_active) then
        raise exception 'Debe permanecer al menos un administrador activo';
    end if;

    update public.profiles set role = new_role, active = new_active
    where id = target_profile_id;

    insert into public.audit_log(admin_user_id, action, details)
    values (
        public.current_finoptima_profile_id(),
        'Actualización de cuenta',
        'Cuenta ' || target_email || '; rol=' || new_role || '; activa=' || new_active::text
    );
end;
$$;

revoke all on function public.admin_update_profile(integer, text, boolean) from public;
revoke all on function public.admin_update_profile(integer, text, boolean) from anon;
grant execute on function public.admin_update_profile(integer, text, boolean) to authenticated;

